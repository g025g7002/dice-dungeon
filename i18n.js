  const LANG_KEY = 'dd_lang';

  function detectInitialLang() {
    try {
      const url = new URLSearchParams(window.location.search).get('lang');
      if (url === 'ja' || url === 'zh') return url;
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === 'ja' || saved === 'zh') return saved;
    } catch (_) {}
    return 'ja'; // 默认日语
  }

  window.I18N = {
    lang: detectInitialLang(),
    t(key, params) {
      let s = (DICT[this.lang] && DICT[this.lang][key]) || DICT.zh[key] || key;
      if (params) {
        for (const k of Object.keys(params)) {
          s = s.split(`{${k}}`).join(String(params[k]));
        }
      }
      return s;
    },
    setLang(lang) {
      this.lang = lang;
      try {
        localStorage.setItem(LANG_KEY, lang);
      } catch (_) {}
      document.documentElement.lang = lang === 'ja' ? 'ja' : 'zh-CN';
      this.applyStatic();
    },
    applyStatic() {
      document.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = this.t(el.getAttribute('data-i18n'));
      });
      document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        el.innerHTML = this.t(el.getAttribute('data-i18n-html'));
      });
      document.title = `${this.t('app.title')} · UNFOLD DUNGEON`;
      const lb = document.getElementById('btnLang');
      if (lb) lb.textContent = this.t('hud.langBtn');
    },
  };

  window.t = (key, params) => window.I18N.t(key, params);
